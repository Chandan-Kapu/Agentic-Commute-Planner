// Build step (runs automatically via wrangler.toml [build]): embeds public/* into src/static.gen.ts
// so the Worker serves the UI itself — no separate static-asset upload needed.
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join, extname, relative } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const pub = join(root, "public");
const TYPES = { ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8", ".svg": "image/svg+xml", ".json": "application/json" };
const files = {};
(function walk(dir) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (TYPES[extname(f)]) files["/" + relative(pub, p)] = { type: TYPES[extname(f)], body: readFileSync(p, "utf8") };
  }
})(pub);
writeFileSync(join(root, "src", "static.gen.ts"),
  "// GENERATED by scripts/embed-static.mjs — do not edit. Source: public/\n" +
  `export const STATIC: Record<string, { type: string; body: string }> = ${JSON.stringify(files)};\n`);
console.log(`embedded ${Object.keys(files).length} files from public/`);
